export function dailyPoem(now = new Date()) {
  const day = Math.floor(Date.UTC(now.getFullYear(), now.getMonth(), now.getDate()) / 86400000) + 719162;
  const [line, dynasty, poet, title, full] = poems[day % poems.length];
  return { line, dynasty, poet, title, full };
}

export function setupPoetry() {
  const byId = (id) => document.getElementById(id);
  let poem;
  let midnight;
  function refresh() {
    clearTimeout(midnight);
    const now = new Date();
    poem = dailyPoem(now);
    byId("poem-line").textContent = poem.line;
    byId("poem-credit").textContent = poem.dynasty + " · " + poem.poet + "《" + poem.title + "》";
    byId("poem-button").title = poem.line + " " + byId("poem-credit").textContent;
    const next = new Date(now);
    next.setHours(24, 0, 0, 50);
    midnight = setTimeout(refresh, next - now);
  }
  byId("poem-button").addEventListener("click", () => {
    byId("poem-title").textContent = poem.title;
    byId("poem-author").textContent = poem.dynasty + " · " + poem.poet;
    byId("poem-full").textContent = poem.full;
    byId("poem-dialog").showModal();
  });
  document.addEventListener("visibilitychange", () => { if (!document.hidden) refresh(); });
  refresh();
}
